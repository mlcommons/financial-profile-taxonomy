#!/usr/bin/env python3
"""Validate the taxonomy and regenerate Markdown tables from the YAML sources.

Single source of truth:
  taxonomy/taxonomy.yaml   four axes + cross-axis platform case
  taxonomy/examples.yaml   worked bounded claims (validated against taxonomy.yaml)

Targets (rewritten in place between generated markers):
  README.md                                           quick-overview
  taxonomy/taxonomy-overview.md                       taxonomy-tree
  taxonomy/axes/autonomy-tier/README.md               tier-table, modifier-table
  taxonomy/axes/operational-design-domain/README.md   business-line-summary
  taxonomy/axes/operational-design-domain/use-cases.md          use-case-catalog
  taxonomy/axes/operational-design-domain/multiplying-factors.md multiplying-factors
  taxonomy/axes/action-class/README.md                action-class-table
  taxonomy/axes/control-envelope/README.md            layer-summary
  taxonomy/axes/control-envelope/<layer>.md           control-table
  taxonomy/examples-overview.md                       examples-overview

Generated regions are delimited by HTML comments:
  <!-- BEGIN GENERATED: <name> -->
  <!-- END GENERATED: <name> -->

Usage:
  python scripts/generate_tables.py          # validate, then regenerate in place
  python scripts/generate_tables.py --check  # validate; exit 1 if any file would change (CI)
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.stderr.write("error: PyYAML is required. Install with: pip install pyyaml\n")
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
TAXONOMY = ROOT / "taxonomy" / "taxonomy.yaml"
EXAMPLES = ROOT / "taxonomy" / "examples.yaml"
AXES_DIR = "taxonomy/axes"

# Expected sizes of the v0.1.0 option universe. Update deliberately when the
# taxonomy changes (a mismatch is a CI failure, not a warning).
EXPECTED = {
    "tiers": 5,
    "modifiers": 6,
    "business_lines": 9,
    "use_cases": 52,
    "action_classes": 12,
    "layers": 6,
    "controls": 55,
    "platform_properties": 6,
}

GENERATED_NOTE = (
    "<!-- This section is generated by scripts/generate_tables.py. "
    "Do not edit by hand. Update {src} instead. -->"
)


# --------------------------------------------------------------------------- #
# Loading and indexing
# --------------------------------------------------------------------------- #

def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def axis(tax: dict, axis_id: str) -> dict:
    for a in tax["axes"]:
        if a["id"] == axis_id:
            return a
    raise KeyError(axis_id)


def index_ids(tax: dict) -> dict[str, str]:
    """Return {canonical_id: kind} for every addressable value."""
    ids: dict[str, str] = {}

    def add(i: str, kind: str) -> None:
        if i in ids:
            raise ValueError(f"duplicate id: {i}")
        ids[i] = kind

    at = axis(tax, "autonomy-tier")
    for t in at["tiers"]:
        add(t["id"], "tier")
    add(at["residual_status"]["id"], "residual-status")
    for m in at["modifiers"]["values"]:
        add(m["id"], "modifier")

    odd = axis(tax, "operational-design-domain")
    for bl in odd["business_lines"]:
        for uc in bl["use_cases"]:
            add(uc["id"], "use-case")

    for c in axis(tax, "action-class")["classes"]:
        add(c["id"], "action-class")

    for layer in axis(tax, "control-envelope")["layers"]:
        for ctl in layer["controls"]:
            add(ctl["id"], "control")
    return ids


# --------------------------------------------------------------------------- #
# Validation
# --------------------------------------------------------------------------- #

def validate(tax: dict, ex: dict) -> list[str]:
    errors: list[str] = []
    try:
        ids = index_ids(tax)
    except ValueError as exc:
        return [str(exc)]

    at = axis(tax, "autonomy-tier")
    odd = axis(tax, "operational-design-domain")
    ac = axis(tax, "action-class")
    ce = axis(tax, "control-envelope")
    plat = tax["cross_axis"][0]

    counts = {
        "tiers": len(at["tiers"]),
        "modifiers": len(at["modifiers"]["values"]),
        "business_lines": len(odd["business_lines"]),
        "use_cases": sum(len(b["use_cases"]) for b in odd["business_lines"]),
        "action_classes": len(ac["classes"]),
        "layers": len(ce["layers"]),
        "controls": sum(len(l["controls"]) for l in ce["layers"]),
        "platform_properties": len(plat["required_properties"]),
    }
    for k, v in EXPECTED.items():
        if counts[k] != v:
            errors.append(f"count mismatch for {k}: expected {v}, found {counts[k]}")

    # Use cases: exactly ODD.1 .. ODD.n, each assigned to one business line.
    # (Business lines follow preprint Section 4.2 order, so treasury_finance
    # (ODD.43-45) is listed before insurance (ODD.41-42).)
    nums = sorted(int(uc["id"].split(".")[1]) for bl in odd["business_lines"] for uc in bl["use_cases"])
    if nums != list(range(1, len(nums) + 1)):
        errors.append(f"use-case IDs are not exactly ODD.1..ODD.{len(nums)}")
    slug = re.compile(r"^[a-z][a-z0-9_]*$")
    for bl in odd["business_lines"]:
        if not slug.match(bl["id"]):
            errors.append(f"business-line id is not a snake_case slug: {bl['id']}")
    for m in at["modifiers"]["values"]:
        if not slug.match(m["id"]):
            errors.append(f"modifier id is not a snake_case slug: {m['id']}")

    # Action classes A1..A12 in order.
    for i, c in enumerate(ac["classes"], start=1):
        if c["id"] != f"A{i}":
            errors.append(f"action-class order break: expected A{i}, found {c['id']}")

    # Control IDs are <layer>.<slug>; list order within a layer is the ordinal.
    ctl_id = re.compile(r"^[a-z_]+\.[a-z][a-z0-9_]*$")
    for layer in ce["layers"]:
        for ctl in layer["controls"]:
            if not ctl_id.match(ctl["id"]) or not ctl["id"].startswith(layer["id"] + "."):
                errors.append(f"control id {ctl['id']} must be '{layer['id']}.<snake_case_slug>'")

    # Examples.
    for e in ex.get("examples", []):
        eid = e.get("id", "<missing id>")

        def check(ref: str, kinds: tuple[str, ...], field: str) -> None:
            if ref not in ids:
                errors.append(f"example {eid}: {field} references unknown id {ref}")
            elif ids[ref] not in kinds:
                errors.append(f"example {eid}: {field} id {ref} is a {ids[ref]}, expected {'/'.join(kinds)}")

        check(e["autonomy_tier"], ("tier", "residual-status"), "autonomy_tier")
        for u in e["odd"].get("use_cases", []):
            check(u, ("use-case",), "odd.use_cases")
        for u in e["odd"].get("out_of_scope_use_cases", []):
            check(u, ("use-case",), "odd.out_of_scope_use_cases")
        plus = e["actions"].get("permitted_classes", [])
        minus = e["actions"].get("prohibited_classes", [])
        for a in plus:
            check(a, ("action-class",), "actions.permitted_classes")
        for a in minus:
            check(a, ("action-class",), "actions.prohibited_classes")
        overlap = sorted(set(plus) & set(minus))
        if overlap:
            errors.append(f"example {eid}: A+ and A- overlap on {overlap}")
        for c in e["controls"].get("catalogue", []):
            check(c, ("control",), "controls.catalogue")
    return errors


# --------------------------------------------------------------------------- #
# Renderers
# --------------------------------------------------------------------------- #

def md_escape(s: str) -> str:
    return " ".join(str(s).split()).replace("|", "\\|")


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(md_escape(c) for c in r) + " |")
    return "\n".join(out)


def r_quick_overview(tax: dict, ex: dict) -> str:
    at, odd, ac, ce = (axis(tax, i) for i in
                       ("autonomy-tier", "operational-design-domain", "action-class", "control-envelope"))
    n_uc = sum(len(b["use_cases"]) for b in odd["business_lines"])
    n_ctl = sum(len(l["controls"]) for l in ce["layers"])
    rows = [
        [f"[{at['symbol']} · {at['name']}](taxonomy/axes/autonomy-tier/README.md)",
         f"{len(at['tiers'])} tiers (T0–T4) + residual status U · {len(at['modifiers']['values'])} modifiers",
         at["summary"]],
        [f"[{odd['symbol']} · {odd['name']}](taxonomy/axes/operational-design-domain/README.md)",
         f"Open set · {n_uc} candidate use cases across {len(odd['business_lines'])} lines of business · "
         f"{len(odd['multiplying_factors'])} multiplying factors",
         odd["summary"]],
        [f"[{ac['symbol']} · {ac['name']}](taxonomy/axes/action-class/README.md)",
         f"{len(ac['classes'])} classes (A1–A12), graded by reversibility & consequence",
         ac["summary"]],
        [f"[{ce['symbol']} · {ce['name']}](taxonomy/axes/control-envelope/README.md)",
         f"{n_ctl} named controls across {len(ce['layers'])} layers",
         ce["summary"]],
    ]
    return table(["Axis", "Option universe", "Question it answers"], rows)


def r_tree(tax: dict, ex: dict) -> str:
    at, odd, ac, ce = (axis(tax, i) for i in
                       ("autonomy-tier", "operational-design-domain", "action-class", "control-envelope"))
    lines = ["Agent Reliability Profile: operating boundary  S(D) = (T, O, A+, A-, C)", "│"]
    # Axis 1
    lines.append(f"├── Axis 1 · {at['symbol']} · {at['name']}")
    lines.append("│   ├── Tiers")
    for t in at["tiers"]:
        flag = "  [high scrutiny]" if t.get("scrutiny") == "high" else ""
        lines.append(f"│   │   ├── {t['id']}  {t['name']}{flag}")
    u = at["residual_status"]
    lines.append(f"│   │   └── {u['id']}   {u['name']} (a status, not a tier)")
    lines.append("│   └── Cross-cutting modifiers")
    mods = at["modifiers"]["values"]
    for i, m in enumerate(mods):
        lines.append(f"│       {'└' if i == len(mods) - 1 else '├'}── {m['name']}")
    lines.append("│")
    # Axis 2
    lines.append(f"├── Axis 2 · {odd['symbol']} · {odd['name']}  (open set)")
    lines.append("│   ├── Use cases by line of business")
    bls = odd["business_lines"]
    for i, bl in enumerate(bls):
        ucs = bl["use_cases"]
        rng = f"{ucs[0]['id']}–{ucs[-1]['id'].split('.')[1]}" if len(ucs) > 1 else ucs[0]["id"]
        lines.append(f"│   │   {'└' if i == len(bls) - 1 else '├'}── {bl['name']} ({len(ucs)})  {rng}")
    lines.append("│   └── Multiplying factors")
    mfs = odd["multiplying_factors"]
    for i, f in enumerate(mfs):
        lines.append(f"│       {'└' if i == len(mfs) - 1 else '├'}── {f['name']} (×{len(f['values'])})")
    lines.append("│")
    # Axis 3
    lines.append(f"├── Axis 3 · {ac['symbol']} · {ac['name']}  (permitted set A+, prohibited set A-)")
    cls = ac["classes"]
    for i, c in enumerate(cls):
        lines.append(f"│   {'└' if i == len(cls) - 1 else '├'}── {c['id']:<4} {c['name']:<32} {c['reversibility']}")
    lines.append("│")
    # Axis 4
    lines.append(f"└── Axis 4 · {ce['symbol']} · {ce['name']}")
    lay = ce["layers"]
    for i, l in enumerate(lay):
        scope = "" if l["applies_to"] == "all" else f"  [{l['applies_to']}]"
        lines.append(f"    {'└' if i == len(lay) - 1 else '├'}── {l['name']} ({len(l['controls'])}){scope}")
    return "```\n" + "\n".join(lines) + "\n```"


def r_tier_table(tax: dict, ex: dict) -> str:
    at = axis(tax, "autonomy-tier")
    rows = [[f"**{t['id']}**" + (" (high scrutiny)" if t.get("scrutiny") == "high" else ""),
             t["does"], t["fallback"], t["example"]] for t in at["tiers"]]
    u = at["residual_status"]
    rows.append([f"**{u['id']}**", f"{u['name']}. {u['description']}", f"{u['fallback']} {u['consequence']}", "—"])
    return table(["Tier", "What the agent does", "Fallback when the agent cannot continue", "Example"], rows)


def r_modifier_table(tax: dict, ex: dict) -> str:
    at = axis(tax, "autonomy-tier")
    rows = [[f"`{m['id']}`", m["name"], m["description"]] for m in at["modifiers"]["values"]]
    return table(["ID", "Modifier", "What it records"], rows)


def r_business_line_summary(tax: dict, ex: dict) -> str:
    odd = axis(tax, "operational-design-domain")
    rows = []
    for bl in odd["business_lines"]:
        ucs = bl["use_cases"]
        rows.append([f"[{bl['name']}](use-cases.md#{bl['id']})", f"`{bl['id']}`", str(len(ucs)),
                     f"{ucs[0]['id']} – {ucs[-1]['id']}"])
    total = sum(len(b["use_cases"]) for b in odd["business_lines"])
    rows.append(["**Total**", "", f"**{total}**", ""])
    return table(["Line of business", "ID", "Use cases", "Use-case IDs"], rows)


def r_use_case_catalog(tax: dict, ex: dict) -> str:
    odd = axis(tax, "operational-design-domain")
    parts = []
    for bl in odd["business_lines"]:
        parts.append(f'<a id="{bl["id"]}"></a>\n\n### {bl["name"]} ({len(bl["use_cases"])}) · `{bl["id"]}`\n')
        parts.append(table(["ID", "Use case"], [[f"`{u['id']}`", u["name"]] for u in bl["use_cases"]]))
        parts.append("")
    return "\n".join(parts).rstrip()


def r_multiplying_factors(tax: dict, ex: dict) -> str:
    odd = axis(tax, "operational-design-domain")
    rows = [[f["name"], f"×{len(f['values'])}", " · ".join(f["values"])] for f in odd["multiplying_factors"]]
    return table(["Factor", "Values", "Range"], rows)


def r_action_class_table(tax: dict, ex: dict) -> str:
    ac = axis(tax, "action-class")
    rows = [[f"**{c['id']}**", c["name"], ", ".join(c["examples"]), c["reversibility"]] for c in ac["classes"]]
    return table(["Class", "Name", "Examples", "Reversibility"], rows)


def r_layer_summary(tax: dict, ex: dict) -> str:
    ce = axis(tax, "control-envelope")
    rows = [[f"[{l['name']}]({l['page']}.md)", str(len(l["controls"])),
             "All deployments" if l["applies_to"] == "all" else l["applies_to"].capitalize(),
             f"`{l['id']}.<slug>`"] for l in ce["layers"]]
    total = sum(len(l["controls"]) for l in ce["layers"])
    rows.append(["**Total**", f"**{total}**", "", ""])
    return table(["Layer", "Controls", "Applies to", "ID pattern"], rows)


def make_control_table(layer_id: str):
    def render(tax: dict, ex: dict) -> str:
        ce = axis(tax, "control-envelope")
        layer = next(l for l in ce["layers"] if l["id"] == layer_id)
        return table(["#", "ID", "Control"],
                     [[str(i), f"`{c['id']}`", c["name"]] for i, c in enumerate(layer["controls"], start=1)])
    return render


def r_examples_overview(tax: dict, ex: dict) -> str:
    ids_to_name = {}
    for c in axis(tax, "action-class")["classes"]:
        ids_to_name[c["id"]] = c["name"]
    for l in axis(tax, "control-envelope")["layers"]:
        for c in l["controls"]:
            ids_to_name[c["id"]] = c["name"]
    for b in axis(tax, "operational-design-domain")["business_lines"]:
        for u in b["use_cases"]:
            ids_to_name[u["id"]] = u["name"]

    parts = [table(
        ["Example", "T", "O", "A+", "A-", "C (catalogue)"],
        [[f"[{e['title']}](#{e['id']})", e["autonomy_tier"], ", ".join(e["odd"]["use_cases"]),
          ", ".join(e["actions"]["permitted_classes"]), ", ".join(e["actions"]["prohibited_classes"]),
          ", ".join(e["controls"]["catalogue"])] for e in ex["examples"]],
    ), ""]
    for e in ex["examples"]:
        parts.append(f'<a id="{e["id"]}"></a>\n\n<details>\n<summary><strong>{e["title"]}</strong> '
                     f'({e["source"]})</summary>\n')
        parts.append(f"> {md_escape(e['claim'])}\n")
        parts.append(f"- **Autonomy tier:** {e['autonomy_tier']}. {md_escape(e['autonomy_notes'])}")
        odd_ids = ", ".join(f"{u} ({ids_to_name[u]})" for u in e["odd"]["use_cases"])
        parts.append(f"- **ODD:** {odd_ids}. {md_escape(e['odd']['description'])}")
        plus = ", ".join(f"{a} {ids_to_name[a]}" for a in e["actions"]["permitted_classes"])
        minus = ", ".join(f"{a} {ids_to_name[a]}" for a in e["actions"]["prohibited_classes"])
        parts.append(f"- **A+:** {plus}")
        parts.append(f"- **A- (proposed mapping):** {minus}. Stated: "
                     f"{'; '.join(e['actions']['prohibited_actions'])}.")
        ctl = ", ".join(f"{c} {ids_to_name[c]}" for c in e["controls"]["catalogue"])
        parts.append(f"- **C (proposed mapping):** {ctl}")
        parts.append("- **Floors:** " + " ".join(e["floors"]))
        parts.append(f"- **Out of scope:** {md_escape(e['out_of_scope'])}")
        parts.append(f"- **Validity:** {md_escape(e['validity'])}")
        parts.append("\n</details>\n")
    return "\n".join(parts).rstrip()


TARGETS: list[tuple[str, str, object, str]] = [
    ("README.md", "quick-overview", r_quick_overview, "taxonomy/taxonomy.yaml"),
    ("taxonomy/taxonomy-overview.md", "taxonomy-tree", r_tree, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/autonomy-tier/README.md", "tier-table", r_tier_table, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/autonomy-tier/README.md", "modifier-table", r_modifier_table, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/operational-design-domain/README.md", "business-line-summary",
     r_business_line_summary, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/operational-design-domain/use-cases.md", "use-case-catalog",
     r_use_case_catalog, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/operational-design-domain/multiplying-factors.md", "multiplying-factors",
     r_multiplying_factors, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/action-class/README.md", "action-class-table", r_action_class_table, "taxonomy/taxonomy.yaml"),
    (f"{AXES_DIR}/control-envelope/README.md", "layer-summary", r_layer_summary, "taxonomy/taxonomy.yaml"),
    ("taxonomy/examples-overview.md", "examples-overview", r_examples_overview, "taxonomy/examples.yaml"),
]
for _layer, _page in (("model", "model"), ("tool", "tool"), ("harness", "harness"), ("environment", "environment"),
                      ("inter_agent", "inter-agent"), ("control_plane", "control-plane")):
    TARGETS.append((f"{AXES_DIR}/control-envelope/{_page}.md", "control-table",
                    make_control_table(_layer), "taxonomy/taxonomy.yaml"))


# --------------------------------------------------------------------------- #
# Region replacement
# --------------------------------------------------------------------------- #

def replace_region(text: str, name: str, body: str, src: str, path: str) -> str:
    pattern = re.compile(
        rf"(<!-- BEGIN GENERATED: {re.escape(name)} -->\n)(.*?)(<!-- END GENERATED: {re.escape(name)} -->)",
        re.DOTALL,
    )
    if not pattern.search(text):
        raise SystemExit(f"error: {path} is missing generated region '{name}'")
    block = GENERATED_NOTE.format(src=src) + "\n\n" + body + "\n\n"
    return pattern.sub(lambda m: m.group(1) + block + m.group(3), text, count=1)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if any generated region is stale")
    args = ap.parse_args()

    tax, ex = load(TAXONOMY), load(EXAMPLES)
    errors = validate(tax, ex)
    if errors:
        for e in errors:
            sys.stderr.write(f"validation error: {e}\n")
        return 1

    pending: dict[str, str] = {}
    for rel, name, render, src in TARGETS:
        path = ROOT / rel
        current = pending.get(rel, path.read_text(encoding="utf-8"))
        pending[rel] = replace_region(current, name, render(tax, ex), src, rel)

    stale = []
    for rel, new in pending.items():
        path = ROOT / rel
        old = path.read_text(encoding="utf-8")
        if old != new:
            stale.append(rel)
            if args.check:
                diff = difflib.unified_diff(old.splitlines(), new.splitlines(), f"a/{rel}", f"b/{rel}", lineterm="")
                sys.stdout.write("\n".join(list(diff)[:60]) + "\n")
            else:
                path.write_text(new, encoding="utf-8")

    if args.check:
        if stale:
            sys.stderr.write(f"\n{len(stale)} file(s) out of date. Run: python scripts/generate_tables.py\n")
            return 1
        print("Taxonomy valid; all generated tables are up to date.")
        return 0
    print(f"Taxonomy valid; regenerated {len(stale)} file(s)." if stale else "Taxonomy valid; nothing to change.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
